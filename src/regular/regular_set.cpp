#include "CU/regular/regular_set.hpp"

#include "CU/regular/regular_set_operations.hpp"

#include <utility>

RegularSet::RegularSet() = default;

RegularSet::RegularSet(RegularSetData data)
    : m_data(std::move(data))
{
    if (m_data.period == 0)
    {
        m_data.periodic.clear();
    }
}

RegularSet::RegularSet(const data_t &finite)
    : m_data{finite, data_t{}, 0}
{
}

RegularSet::RegularSet(num_t d)
{
    if (d != 0)
    {
        m_data.periodic.insert(0);
        m_data.period = d;
    }
}

const RegularSetData &RegularSet::data() const
{
    return m_data;
}

RegularSetData &RegularSet::data()
{
    return m_data;
}

void RegularSet::minimize()
{
    if (m_data.period == 0)
    {
        m_data.periodic.clear();
        return;
    }

    // Remove periodic bases covered by another base with the same residue.
    data_t new_periodic;
    for (num_t b : m_data.periodic)
    {
        bool redundant = false;
        for (num_t other : m_data.periodic)
        {
            if (other == b)
            {
                continue;
            }
            if (b >= other && (b - other) % m_data.period == 0)
            {
                redundant = true;
                break;
            }
        }
        if (!redundant)
        {
            new_periodic.insert(b);
        }
    }
    m_data.periodic = std::move(new_periodic);

    // Remove finite elements already generated by the periodic part.
    data_t new_finite;
    for (num_t x : m_data.finite)
    {
        bool covered = false;
        for (num_t b : m_data.periodic)
        {
            if (x >= b && (x - b) % m_data.period == 0)
            {
                covered = true;
                break;
            }
        }
        if (!covered)
        {
            new_finite.insert(x);
        }
    }
    m_data.finite = std::move(new_finite);

    if (m_data.periodic.empty())
    {
        m_data.period = 0;
    }
}

bool RegularSet::contains(num_t value) const
{
    if (m_data.finite.count(value))
    {
        return true;
    }
    if (m_data.period == 0)
    {
        return false;
    }
    for (num_t b : m_data.periodic)
    {
        if (value >= b && (value - b) % m_data.period == 0)
        {
            return true;
        }
    }
    return false;
}

RegularSet operator|(const RegularSet &lhs, const RegularSet &rhs)
{
    RegularSetOperations ops;
    return RegularSet(ops.unite(lhs.data(), rhs.data()));
}

RegularSet operator+(const RegularSet &lhs, const RegularSet &rhs)
{
    RegularSetOperations ops;
    return RegularSet(ops.sum(lhs.data(), rhs.data()));
}

RegularSet operator&(const RegularSet &lhs, const RegularSet &rhs)
{
    RegularSetOperations ops;
    return RegularSet(ops.intersect(lhs.data(), rhs.data()));
}

RegularSet difference(const RegularSet &lhs, const RegularSet &rhs)
{
    RegularSetOperations ops;
    return RegularSet(ops.difference(lhs.data(), rhs.data()));
}