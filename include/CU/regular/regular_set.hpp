#ifndef CU_REGULAR_SET_HPP
#define CU_REGULAR_SET_HPP

#include "CU/regular/regular_set_data.hpp"

/**
 * @brief Regular set of natural numbers.
 *
 * Encapsulates a @ref RegularSetData and provides a small set of
 * convenience operations. 
 */
class RegularSet
{
public:
    RegularSet();
    explicit RegularSet(RegularSetData data);

    /**
     * @brief Builds a finite regular set (period is zero, periodic part is empty).
     */
    explicit RegularSet(const data_t &finite);

    /**
     * @brief Builds the regular set [d] = {0, d, 2d, 3d, ...}.
     *
     * If @p d is zero, the empty set is constructed.
     */
    explicit RegularSet(num_t d);

    const RegularSetData &data() const;
    RegularSetData &data();

    /**
     * @brief Minimizes the internal representation without changing the set.
     *
     * Removes redundant periodic bases and finite elements that are
     * already generated by the periodic part.
     */
    void minimize();
    
    /// @brief Membership test.
    bool contains(num_t value) const;

    friend RegularSet operator|(const RegularSet &lhs, const RegularSet &rhs);
    friend RegularSet operator+(const RegularSet &lhs, const RegularSet &rhs);
    friend RegularSet operator&(const RegularSet &lhs, const RegularSet &rhs);
    friend RegularSet difference(const RegularSet &lhs, const RegularSet &rhs);

private:
    RegularSetData m_data;
};

#endif // CU_REGULAR_SET_HPP